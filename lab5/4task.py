# Ввод массива
arr = list(map(int, input("Введите элементы массива через пробел: ").split()))

# 1. Запрос числа для поиска
number = int(input("Введите число для поиска: "))

# 2–4. Проверка наличия и вывод результата
if number in arr:
    index = arr.index(number)
    print("Число найдено. Индекс:", index)
else:
    print("Число в массиве не найдено.")
